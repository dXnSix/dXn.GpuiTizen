//! `cargo xtask gpui-fast-release [--verify]`: gpui-fast's release workspace from the fork's
//! `tizen` branch (`bun script/prepare-release.ts --tag v0.1.13`), checked with `cargo check`.
//! Without `--verify` its exact output is committed to the fork's local `tizen-release` branch
//! through a git worktree; with `--verify` nothing is committed, and a Cargo config patching all
//! nine `gpui-fast-*` crates with `path` entries into the release workspace is written to
//! `artifacts-temp/gpui-fast-patch.toml` and proven with `cargo tree -i gpui-fast`.
//!
//! The patch entries, the commit message and the `cargo tree` verdict are pure functions tested
//! by `release::tests`; `main.rs` runs Bun, Cargo and Git.

use std::path::Path;

/// The release tag `tizen` is built on (design `d05-gpui-fast-pin`).
pub const TAG: &str = "v0.1.13";
/// The branch the release workspace is generated from, and the one it is committed to.
pub const SOURCE_BRANCH: &str = "tizen";
pub const RELEASE_BRANCH: &str = "tizen-release";
/// `prepare-release.ts`'s output directory, relative to the gpui-fast checkout.
pub const RELEASE_WORKSPACE: &str = "target/release-workspace";
/// The patch config, relative to this repository.
pub const PATCH_CONFIG: &str = "artifacts-temp/gpui-fast-patch.toml";
/// The line the verification prints.
pub const OK_LINE: &str = "gpui-fast patch ok";

/// The nine crates of a gpui-fast release: (release-workspace directory, crates.io package).
pub const CRATES: [(&str, &str); 9] = [
    ("gpui_macros", "gpui-fast-macros"),
    ("gpui", "gpui-fast"),
    ("gpui_apple", "gpui-fast-apple"),
    ("gpui_wgpu", "gpui-fast-wgpu"),
    ("gpui_macos", "gpui-fast-macos"),
    ("gpui_linux", "gpui-fast-linux"),
    ("gpui_windows", "gpui-fast-windows"),
    ("gpui_web", "gpui-fast-web"),
    ("gpui_platform", "gpui-fast-platform"),
];

/// A Cargo config patching every `gpui-fast-*` crate from crates.io with the release workspace.
pub fn patch_config(release_workspace: &Path) -> String {
    let mut out = String::from(
        "# Generated by `cargo xtask gpui-fast-release --verify`: gpui-fast's release workspace from\n\
         # the fork's `tizen` branch. Use with `cargo --config artifacts-temp/gpui-fast-patch.toml ...`.\n\
         [patch.crates-io]\n",
    );
    for (dir, package) in CRATES {
        let path = release_workspace.join(dir);
        let path = path.display().to_string().replace('\\', "/");
        out.push_str(&format!("{package} = {{ path = \"{path}\" }}\n"));
    }
    out
}

/// The `tizen-release` commit message for a release generated from `tizen` at `source_sha`.
pub fn commit_message(source_sha: &str) -> String {
    format!(
        "release: gpui-fast {} for Tizen\n\nGenerated by `bun script/prepare-release.ts --tag {TAG}` from `{SOURCE_BRANCH}` at {source_sha}\n(`cargo xtask gpui-fast-release` in dXn.GpuiTizen); not edited by hand.",
        TAG.trim_start_matches('v')
    )
}

/// Where the patched resolution keeps its lockfile, so `--verify` never rewrites `Cargo.lock`.
pub const SCRATCH_LOCK: &str = "artifacts-temp/locks/gpui-fast-patch/Cargo.lock";

/// Checks the lockfile the patched resolution wrote: the graph is not empty, `gpui-fast` comes
/// from a path (the release workspace), and no patch Cargo left unused (`[[patch.unused]]`) is
/// for a crate the graph still holds, which would then come from crates.io. Patches of crates the
/// graph never contains (the desktop platforms) are unused by design: all nine are always patched
/// together. The lockfile covers every target, not only the one `cargo tree` printed.
pub fn verify_lock(lock: &str) -> Result<(), String> {
    let value: toml::Value = lock
        .parse()
        .map_err(|e| format!("the patched lockfile does not parse: {e}"))?;
    let packages: Vec<&toml::Value> = value
        .get("package")
        .and_then(toml::Value::as_array)
        .map(|a| a.iter().collect())
        .unwrap_or_default();
    if packages.is_empty() {
        return Err("the patched lockfile holds no packages".to_owned());
    }
    let name = |p: &&toml::Value| {
        p.get("name")
            .and_then(toml::Value::as_str)
            .map(str::to_owned)
    };
    let names: std::collections::BTreeSet<String> = packages.iter().filter_map(name).collect();
    let unused: Vec<String> = value
        .get("patch")
        .and_then(|p| p.get("unused"))
        .and_then(toml::Value::as_array)
        .map(|a| a.iter().filter_map(|p| name(&p)).collect())
        .unwrap_or_default();
    let used_but_unpatched: Vec<&String> = unused.iter().filter(|u| names.contains(*u)).collect();
    if !used_but_unpatched.is_empty() {
        return Err(format!(
            "the graph uses {} but its patch was not used (it resolves from crates.io)",
            used_but_unpatched
                .iter()
                .map(|s| s.as_str())
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    let gpui = packages
        .iter()
        .find(|p| name(p).as_deref() == Some("gpui-fast"));
    match gpui {
        None => Err("gpui-fast is not in the graph".to_owned()),
        Some(p) if p.get("source").is_some() => Err(format!(
            "gpui-fast still comes from {}",
            p["source"].as_str().unwrap_or("a registry")
        )),
        Some(_) => Ok(()),
    }
}

/// Checks `cargo tree -i gpui-fast` with the patch config: `gpui-fast` must resolve to the release
/// workspace's `gpui` directory.
pub fn verify_tree(stdout: &str, release_workspace: &Path) -> Result<(), String> {
    let expected = release_workspace.join("gpui");
    let expected = expected.display().to_string();
    let root = stdout
        .lines()
        .find(|line| !line.trim().is_empty())
        .unwrap_or_default();
    let resolved = root.starts_with("gpui-fast v") && root.contains(&format!("({expected})"));
    if resolved {
        Ok(())
    } else {
        Err(format!(
            "gpui-fast does not resolve to {expected}; cargo tree printed `{root}`"
        ))
    }
}

/// Whether a Cargo command line uses the gpui-fast patch config (`--config <...>/gpui-fast-patch.toml`
/// or `--config=...`). Such builds resolve into [`SCRATCH_LOCK`] so `Cargo.lock` never records the
/// local path patch.
pub fn uses_patch_config(cargo_args: &[String]) -> bool {
    let is_patch = |value: &str| value.trim_matches('\'').ends_with("gpui-fast-patch.toml");
    cargo_args.iter().enumerate().any(|(i, arg)| {
        arg.strip_prefix("--config=").is_some_and(is_patch)
            || (arg == "--config" && cargo_args.get(i + 1).is_some_and(|v| is_patch(v)))
    })
}

