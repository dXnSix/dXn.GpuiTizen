pub const RELEASE_BRANCH: &str = "tizen-release";
/// `prepare-release.ts`'s output directory, relative to the gpui-fast checkout.
pub const RELEASE_WORKSPACE: &str = "target/release-workspace";
/// The patch config, relative to this repository.
pub const PATCH_CONFIG: &str = "artifacts-temp/gpui-fast-patch.toml";
/// The line the verification prints.
pub const OK_LINE: &str = "gpui-fast patch ok";

